export function art(name, className = "") {
  const { colours, rows } = ART[name];
  const svg = document.createElementNS(NS, "svg");
  svg.setAttribute("viewBox", `0 0 ${rows[0].length} ${rows.length}`);
  svg.setAttribute("class", `art ${className}`.trim());
  svg.setAttribute("aria-hidden", "true");
  for (const [char, colour] of Object.entries(colours)) {
    const path = document.createElementNS(NS, "path");
    path.setAttribute("d", pathFor(rows, char));
    path.setAttribute("class", `c-${colour}`);
    svg.append(path);
  }
  return svg;
}
