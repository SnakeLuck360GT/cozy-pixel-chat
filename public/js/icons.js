// "Off" versions (muted mic, camera off) get a diagonal slash with a gap
// beside it so it reads against the icon.
function slashed(rows) {
  return rows.map((row, y) =>
    [...row].map((c, x) => (x === y || x === y + 1 ? "#" : x === y + 2 ? "." : c)).join(""),
  );
}
ICONS.micOff = slashed(ICONS.mic);
ICONS.videoOff = slashed(ICONS.video);

const NS = "http://www.w3.org/2000/svg";

// Rows of "#" become one path: runs of filled pixels merge into rectangles.
function pathFor(rows, char = "#") {
  let d = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== char) continue;
      let end = x;
      while (row[end + 1] === char) end++;
      d += `M${x} ${y}h${end - x + 1}v1h-${end - x + 1}z`;
      x = end;
    }
  });
  return d;
}

export function icon(name, className = "") {
  const rows = ICONS[name];
  const svg = document.createElementNS(NS, "svg");
  svg.setAttribute("viewBox", `0 0 ${rows[0].length} ${rows.length}`);
  svg.setAttribute("class", `icon ${className}`.trim());
  svg.setAttribute("aria-hidden", "true");
  const path = document.createElementNS(NS, "path");
  path.setAttribute("d", pathFor(rows));
  svg.append(path);
  return svg;
}

